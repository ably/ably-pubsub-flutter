#!/usr/bin/env bash
#
# Runs the plugin's XCTest suite on an iOS simulator.
#
# The plugin's Package.swift depends on a `FlutterFramework` package at
# `../FlutterFramework`. When an app builds the plugin, the Flutter tool puts an
# empty stub there and the app's own build settings supply Flutter.framework. To
# run the tests standalone, this script generates that sibling package itself,
# wrapping the engine's Flutter.xcframework from the active Flutter SDK.
#
# Usage: ios/run_unit_tests.sh [simulator-udid]
# With no UDID, the first available iPhone simulator is used.

set -euo pipefail

ios_dir="$(cd "$(dirname "$0")" && pwd)"
framework_package="$ios_dir/FlutterFramework"

flutter precache --ios >/dev/null
flutter_root="$(flutter --version --machine | python3 -c 'import json, sys; print(json.load(sys.stdin)["flutterRoot"])')"
engine_xcframework="$flutter_root/bin/cache/artifacts/engine/ios/Flutter.xcframework"
if [[ ! -d "$engine_xcframework" ]]; then
  echo "error: Flutter engine not found at $engine_xcframework" >&2
  exit 1
fi

rm -rf "$framework_package"
mkdir -p "$framework_package/Sources/FlutterFramework"
ln -s "$engine_xcframework" "$framework_package/Flutter.xcframework"
cat > "$framework_package/Sources/FlutterFramework/FlutterFramework.swift" <<'EOF'
@_exported import Flutter
EOF
cat > "$framework_package/Package.swift" <<'EOF'
// swift-tools-version: 5.9
// Generated by run_unit_tests.sh. Do not edit or commit.
import PackageDescription

let package = Package(
    name: "FlutterFramework",
    platforms: [.iOS("15.0")],
    products: [
        .library(name: "FlutterFramework", targets: ["FlutterFramework"])
    ],
    targets: [
        .target(name: "FlutterFramework", dependencies: ["Flutter"]),
        .binaryTarget(name: "Flutter", path: "Flutter.xcframework"),
    ]
)
EOF

simulator_id="${1:-}"
if [[ -z "$simulator_id" ]]; then
  # awk reads all of its input rather than exiting early, so simctl cannot be
  # killed by SIGPIPE and fail the pipeline.
  simulator_id="$(xcrun simctl list devices available | awk '
    /iPhone/ && !id && match($0, /[0-9A-F]{8}-([0-9A-F]{4}-){3}[0-9A-F]{12}/) { id = substr($0, RSTART, RLENGTH) }
    END { print id }')"
  if [[ -z "$simulator_id" ]]; then
    echo "error: no available iPhone simulator found; pass a simulator UDID as the first argument" >&2
    exit 1
  fi
fi

cd "$ios_dir/ably_pubsub_device_flutter"
xcodebuild test \
  -scheme ably_pubsub_device_flutter \
  -destination "id=$simulator_id" \
  CODE_SIGNING_ALLOWED=NO
